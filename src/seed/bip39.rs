use bip39::{Language, Mnemonic};
use zeroize::Zeroizing;

use crate::error::{KeyError, Result};

pub fn to_seed(phrase: &str, passphrase: &str) -> Result<Zeroizing<[u8; 64]>> {
    let mnemonic = Mnemonic::parse_in(Language::English, phrase)
        .map_err(|e| KeyError::InvalidMnemonic(e.to_string()))?;

    Ok(Zeroizing::new(mnemonic.to_seed(passphrase)))
}

#[cfg(test)]
mod tests {
    use super::{KeyError, to_seed};

    const PHRASE: &str = "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";

    #[test]
    fn matches_bip39_vector_with_passphrase() {
        let expected: [u8; 64] = [
            0xc5, 0x52, 0x57, 0xc3, 0x60, 0xc0, 0x7c, 0x72, 0x02, 0x9a, 0xeb, 0xc1, 0xb5, 0x3c,
            0x05, 0xed, 0x03, 0x62, 0xad, 0xa3, 0x8e, 0xad, 0x3e, 0x3e, 0x9e, 0xfa, 0x37, 0x08,
            0xe5, 0x34, 0x95, 0x53, 0x1f, 0x09, 0xa6, 0x98, 0x75, 0x99, 0xd1, 0x82, 0x64, 0xc1,
            0xe1, 0xc9, 0x2f, 0x2c, 0xf1, 0x41, 0x63, 0x0c, 0x7a, 0x3c, 0x4a, 0xb7, 0xc8, 0x1b,
            0x2f, 0x00, 0x16, 0x98, 0xe7, 0x46, 0x3b, 0x04,
        ];

        assert_eq!(*to_seed(PHRASE, "TREZOR").unwrap(), expected);
    }

    #[test]
    fn derives_seed_with_empty_passphrase() {
        let expected: [u8; 64] = [
            0x5e, 0xb0, 0x0b, 0xbd, 0xdc, 0xf0, 0x69, 0x08, 0x48, 0x89, 0xa8, 0xab, 0x91, 0x55,
            0x56, 0x81, 0x65, 0xf5, 0xc4, 0x53, 0xcc, 0xb8, 0x5e, 0x70, 0x81, 0x1a, 0xae, 0xd6,
            0xf6, 0xda, 0x5f, 0xc1, 0x9a, 0x5a, 0xc4, 0x0b, 0x38, 0x9c, 0xd3, 0x70, 0xd0, 0x86,
            0x20, 0x6d, 0xec, 0x8a, 0xa6, 0xc4, 0x3d, 0xae, 0xa6, 0x69, 0x0f, 0x20, 0xad, 0x3d,
            0x8d, 0x48, 0xb2, 0xd2, 0xce, 0x9e, 0x38, 0xe4,
        ];

        assert_eq!(*to_seed(PHRASE, "").unwrap(), expected);
    }

    #[test]
    fn rejects_a_phrase_with_invalid_checksum() {
        let invalid = PHRASE.replace("about", "abandon");

        assert!(matches!(
            to_seed(&invalid, "TREZOR"),
            Err(KeyError::InvalidMnemonic(_))
        ));
    }
}
